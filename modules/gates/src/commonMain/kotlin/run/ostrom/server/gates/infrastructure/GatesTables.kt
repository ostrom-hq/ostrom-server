package run.ostrom.server.gates.infrastructure

import run.ostrom.server.kernel.database.instant
import org.jetbrains.exposed.v1.core.Table

/*
 * The tables of [GatesMigrations], as Exposed reads and writes them. The migrations create the schema; these objects
 * only name its columns and their types, and never create anything (no `SchemaUtils`). Every one holds an
 * organization's rows under row-level security, read and written in `JdbcDatabase.inOrg` (migration 10 grants them to
 * the tenant role), each query filtering on the organization too.
 */

/** The gates: one per boundary action asked, its JSON columns written by the module's own serializer. */
internal object GatesGates : Table("gates_gates") {
    val id = uuid("id")
    val orgId = uuid("org_id")
    val key = text("gate_key")
    val subject = text("subject")
    val node = text("node").nullable()
    val label = text("label")
    val mode = text("mode")
    val status = text("status")
    val askedBy = text("asked_by")
    val askedVia = text("asked_via")
    val sessionIds = text("session_ids")
    val launchIds = text("launch_ids")
    val shownDigest = text("shown_digest")
    val evidence = text("evidence")
    val decidedBy = text("decided_by").nullable()
    val decidedAt = instant("decided_at").nullable()
    val selfApproved = bool("self_approved")
    val receiptId = text("receipt_id").nullable()
    val reservedBy = text("reserved_by").nullable()
    val reservedAt = instant("reserved_at").nullable()
    val consumedAt = instant("consumed_at").nullable()
    val releasedAt = instant("released_at").nullable()
    val createdAt = instant("created_at")
    val unlinkedAuthor = long("unlinked_author").nullable()
    val note = text("note").nullable()

    override val primaryKey = PrimaryKey(id)
}

/** The approval requests: one per approver of a gate, in their order ([position]). */
internal object GatesRequests : Table("gates_requests") {
    val id = uuid("id")
    val gateId = uuid("gate_id")
    val orgId = uuid("org_id")
    val position = integer("position")
    val approverId = text("approver_id")

    /** The lowered approver (migration 3), generated by the database: never written, compared with a leakproof `=`. */
    val approverKey = text("approver_key").databaseGenerated()
    val status = text("status")
    val answeredAt = instant("answered_at").nullable()
    val channel = text("channel").nullable()
    val createdAt = instant("created_at")

    override val primaryKey = PrimaryKey(id)
}

/** The sessions that asked or joined each gate (migration 3). */
internal object GatesSessions : Table("gates_sessions") {
    val orgId = uuid("org_id")
    val sessionId = text("session_id")
    val gateId = uuid("gate_id")

    override val primaryKey = PrimaryKey(orgId, sessionId, gateId)
}

/** The sessions whose end read their gates (migration 8). */
internal object GatesSessionEnds : Table("gates_session_ends") {
    val orgId = uuid("org_id")
    val sessionId = text("session_id")
    val endedAt = instant("ended_at")

    override val primaryKey = PrimaryKey(orgId, sessionId)
}
