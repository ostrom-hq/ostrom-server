// The shared kernel every functional module builds on: configuration, logs, database and migrations, uniform
// HTTP errors, token authentication, the instance signing key, the ServerModule contract and observability (traces,
// metrics and logs through ostrom-core's telemetry module).
plugins {
    id("ostrom.native-module")
}

// The server version (root build.gradle.kts, `-PostromVersion` in CI), written into a generated source at build time:
// `/health`, `/api/v1/instance`, `/api/v1/capabilities`, the start-up logs and the telemetry's `service.version`.
val generatedBuildInfo = layout.buildDirectory.dir("generated/build-info")
val generateBuildInfo by tasks.registering {
    val version = project.version.toString()
    val output = generatedBuildInfo
    inputs.property("version", version)
    outputs.dir(output)
    doLast {
        val file = output.get().file("run/ostrom/server/kernel/BuildInfo.kt").asFile
        file.parentFile.mkdirs()
        file.writeText(
            """
            |// SPDX-License-Identifier: Apache-2.0
            |// Generated by kernel/build.gradle.kts (generateBuildInfo): do not edit.
            |package run.ostrom.server.kernel
            |
            |/** The server version: `-PostromVersion` of the build (a release tag, `0.0.0-edge.…` on main), `0.0.0-dev` locally. */
            |const val SERVER_VERSION: String = "$version"
            |
            """.trimMargin(),
        )
    }
}

kotlin {
    sourceSets {
        commonMain {
            // A top-level constant: inlined where read, no class line for Kover to measure.
            kotlin.srcDir(generateBuildInfo)
        }
        commonMain.dependencies {
            // The contract's models the kernel answers with (`Capabilities`) and the feature keys every module lists.
            api(libs.ostrom.api)
            api(libs.ktor.server.core)
            api(libs.ktor.server.content.negotiation)
