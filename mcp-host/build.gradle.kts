// The MCP stdio host (docs/mcp-host.md): a small HTTP service that runs the organizations' MCP servers published on
// npm or PyPI as supervised child processes, for the server's MCP relay. It depends on no other module: no database,
// no secrets key, no Kubernetes token. Its logic is in commonMain; the processes (ProcessBuilder, ProcessHandle,
// /proc) and the entry point are in jvmMain, and it ships as a JVM application.
plugins {
    id("ostrom.native-module")
}

// The host's version, the server's (`-PostromVersion`), answered by GET /v1/status.
val generatedBuildInfo = layout.buildDirectory.dir("generated/build-info")
val generateBuildInfo by tasks.registering {
    val version = project.version.toString()
    val output = generatedBuildInfo
    inputs.property("version", version)
    outputs.dir(output)
    doLast {
        val file = output.get().file("run/ostrom/mcphost/BuildInfo.kt").asFile
        file.parentFile.mkdirs()
        file.writeText(
            """
            |// SPDX-License-Identifier: Apache-2.0
            |// Generated by mcp-host/build.gradle.kts (generateBuildInfo): do not edit.
            |package run.ostrom.mcphost
            |
            |/** The host version: the server's, `-PostromVersion` of the build, `0.0.0-dev` locally. */
            |const val HOST_VERSION: String = "$version"
            |
            """.trimMargin(),
        )
    }
}

kotlin {
    sourceSets {
        commonMain {
            kotlin.srcDir(generateBuildInfo)
        }
        commonMain.dependencies {
            implementation(libs.ktor.server.core)
            implementation(libs.ktor.server.cio)
            implementation(libs.cryptography.core)
        }
        jvmMain.dependencies {
            implementation(libs.cryptography.jdk)
        }
        commonTest.dependencies {
            implementation(libs.ktor.server.test.host)
        }
    }
}

// The host ships as a JVM application, the direction the whole server takes: its jar and its runtime classpath in
// build/install/ostrom-mcp-host/lib, which mcp-host/Dockerfile copies.
val installHost by tasks.registering(Sync::class) {
    from(tasks.named("jvmJar"))
    from(configurations.named("jvmRuntimeClasspath"))
    into(layout.buildDirectory.dir("install/ostrom-mcp-host/lib"))
}

// The host's tests run the real launch path against a Node.js fixture installed as `npx` and `uvx` (NodeFixtureTest).
tasks.named<Test>("jvmTest") {
    environment("OSTROM_MCP_HOST_TEST_NODE", providers.environmentVariable("OSTROM_MCP_HOST_TEST_NODE").orElse("").get())
}

// The entry point reads the environment and serves until SIGTERM: it is run by the image's smoke test
// (.github/workflows/mcp-host-image.yml), not by a unit test.
kover {
    reports {
        filters {
            excludes {
                classes("run.ostrom.mcphost.MainKt", "run.ostrom.mcphost.MainKt$*")
            }
        }
    }
}
