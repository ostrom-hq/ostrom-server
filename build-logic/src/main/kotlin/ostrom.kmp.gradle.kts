// Convention for every Kotlin module of Ostrom (docs/CONVENTIONS.md sections 7, 8, 9 and 10).
// A module applies `id("ostrom.kmp")` and declares its own dependencies; nothing else goes in its build file.
//
// Native targets come from the property `ostrom.nativeTargets`, read per project, so that a project's own
// gradle.properties overrides the repository's:
//   ostrom-core, ostrom-cli: macosArm64,linuxX64,linuxArm64,mingwX64
//   ostrom-server:           none (the server runs on the JVM, docs/decisions/0001)
//   ostrom-server runner/:   linuxX64,linuxArm64,macosArm64 (runner/gradle.properties)
// The jvm() target always exists: the server's runtime, and the tests and Kover coverage of every project.

import io.gitlab.arturbosch.detekt.Detekt
import kotlinx.kover.gradle.plugin.dsl.CoverageUnit

plugins {
    id("org.jetbrains.kotlin.multiplatform")
    id("org.jetbrains.kotlin.plugin.serialization")
    id("org.jetbrains.kotlinx.kover")
    id("io.gitlab.arturbosch.detekt")
}

val libs = the<VersionCatalogsExtension>().named("libs")
fun lib(alias: String) = libs.findLibrary(alias).get()

val allNativeTargets = setOf("macosArm64", "linuxX64", "linuxArm64", "mingwX64")
val nativeTargets = (findProperty("ostrom.nativeTargets")?.toString() ?: allNativeTargets.joinToString(","))
    .split(',').map(String::trim).filter(String::isNotEmpty).toSet()
require(allNativeTargets.containsAll(nativeTargets)) {
    "ostrom.nativeTargets must be a comma-separated subset of $allNativeTargets (or empty), got $nativeTargets."
}

kotlin {
    jvmToolchain(21)
    jvm {
        testRuns.named("test") { executionTask.configure { useJUnitPlatform() } }
    }
    if ("macosArm64" in nativeTargets) macosArm64()
    if ("linuxX64" in nativeTargets) linuxX64()
    if ("linuxArm64" in nativeTargets) linuxArm64()
    if ("mingwX64" in nativeTargets) mingwX64()

    compilerOptions {
        optIn.addAll("kotlin.uuid.ExperimentalUuidApi", "kotlin.time.ExperimentalTime")
        freeCompilerArgs.add("-Xexpect-actual-classes")
    }

    sourceSets {
        commonMain.dependencies {
            implementation(lib("coroutines-core"))
            implementation(lib("serialization-json"))
        }
        commonTest.dependencies {
            implementation(kotlin("test"))
            implementation(lib("coroutines-test"))
        }
        jvmTest.dependencies {
            runtimeOnly(lib("junit-jupiter-engine"))
            runtimeOnly(lib("junit-platform-launcher"))
        }
    }
}

// 100 % of lines and branches of commonMain, measured through the jvm() test run (BRIEF, rule TESTS).
// An exclusion is added here with a one-line reason, and reviewed.
kover {
    reports {
        filters {
            excludes {
                // Generated by the kotlinx.serialization plugin; each DTO's (de)serialization is tested through its
                // golden JSON round-trip, not branch by branch inside the generated code.
                classes("*\$\$serializer")
                // A @Serializable class is a contract without logic (CONVENTIONS 5); the plugin also writes into it a
                // deserialization constructor whose missing-field check can never fail for a class without required
                // fields, a branch no test can reach. Its JSON shape is tested by the round-trip of its routes.
                annotatedBy("kotlinx.serialization.Serializable")
                // Compatibility bridges the compiler writes for an interface's default methods on the JVM: the test
                // target never calls them (the default methods themselves are measured).
                classes("*\$DefaultImpls")
            }
        }
        verify {
            rule {
                minBound(100, CoverageUnit.LINE)
                minBound(100, CoverageUnit.BRANCH)
            }
        }
    }
}

detekt {
    buildUponDefaultConfig = true
    config.setFrom(rootProject.file("config/detekt/detekt.yml"))
    source.setFrom(fileTree("src") { include("**/*.kt") })
    parallel = true
}

tasks.withType<Detekt>().configureEach {
    jvmTarget = "21"
    reports {
        html.required.set(true)
        sarif.required.set(true)
    }
}

// Every test is reported as it runs, with its output: a native test that hangs is then visible in the CI log.
tasks.withType<AbstractTestTask>().configureEach {
    testLogging {
        events("started", "passed", "skipped", "failed")
        showStandardStreams = true
        exceptionFormat = org.gradle.api.tasks.testing.logging.TestExceptionFormat.FULL
    }
}
