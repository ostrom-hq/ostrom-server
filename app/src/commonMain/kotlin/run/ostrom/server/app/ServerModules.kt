/**
 * Every functional module, in dependency order: migrations and initialization run in this order, so a module comes
 * after the modules whose tables it references. Each module owner adds or edits only its own line. The enterprise
 * modules of `ee/modules/` come last ([eeModules], generated by app/build.gradle.kts, empty in an Apache-2.0 build).
 *
 * @return The modules.
 */
fun serverModules(): List<ServerModule> = listOf(
    InstanceModule,
    IdentityModule,
    OrgsModule,
    ReceiptsModule,
    GatesModule,
    SessionsModule,
    LaunchesModule,
    CompilerModule,
    RulesModule,
    WorkflowRunsModule,
    McpRelayModule,
    SecretsModule,
    // After secrets (it seals the settings with the secrets key) and identity (the setup link's person, the audit).
    AdminModule,
    // The feed the other modules publish to, through the kernel's OrgEventPublisher.
    EventsModule,
    CloudModule,
    UsageModule,
    GatewayModule,
    BudgetsModule,
    BillingModule,
    RunnersModule,
    AutomationsModule,
    ArtifactsModule,
    SkillsModule,
    HooksModule,
    // After the sessions, automations (waits) and artifacts it reads.
    TodosModule,
    GitHubIntegrationModule,
    SlackIntegrationModule,
    SharingModule,
    ImportModule,
    ReportsModule,
    // After the modules whose governance writes it holds (rules, compiler, gateway).
    GovernanceModule,
    NotificationsModule,
) + eeModules()
