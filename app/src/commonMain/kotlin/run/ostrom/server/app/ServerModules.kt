/**
 * Every functional module, in dependency order: migrations and initialization run in this order, so a module comes
 * after the modules whose tables it references. Each module owner adds or edits only its own line. The enterprise
 * modules of `ee/modules/` come last ([eeModules], generated by app/build.gradle.kts, empty in an AGPL build).
 *
 * @return The modules.
 */
fun serverModules(): List<ServerModule> = listOf(
    InstanceModule,
    IdentityModule,
    OrgsModule,
    ReceiptsModule,
    GatesModule,
    SessionsModule,
    LaunchesModule,
    CompilerModule,
    RulesModule,
    WorkflowRunsModule,
    McpRelayModule,
    SecretsModule,
    UsageModule,
    GatewayModule,
    BudgetsModule,
    BillingModule,
    RunnersModule,
    AutomationsModule,
    ArtifactsModule,
    // After the sessions, automations (waits) and artifacts it reads.
    TodosModule,
    GitHubIntegrationModule,
    SlackIntegrationModule,
    SharingModule,
    ImportModule,
    ReportsModule,
    // After the modules whose governance writes it holds (rules, compiler, gateway).
    GovernanceModule,
    NotificationsModule,
) + eeModules()
