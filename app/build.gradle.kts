// The server application: `ostrom-server` serves HTTP on Ktor's CIO engine (role checked, migrations verified, graceful
// drain on SIGTERM), `ostrom-server migrate` applies every module's migrations with the owner's credentials, and
// `ostrom-server seed-test-account` creates a QA account. Depends on every module of modules/, and on the enterprise
// modules of ee/modules/ when that directory is present (an Apache-2.0 build without ee/ compiles the same code with none).
// The entry point is the JVM's (jvmMain, docs/decisions/0001), packaged into the image by image/.
plugins {
    id("ostrom.native-module")
}

// Enterprise modules: each ee/modules/<name>/ee-module.properties names its ServerModule object; the app gets a
// generated `eeModules()` listing them (empty without ee/), appended to `serverModules()`. The list is written at
// build time, so no ServiceLoader or reflection is needed.
val eeProjects = rootProject.subprojects.filter { it.path.startsWith(":ee:modules:") }.sortedBy { it.path }
val eeModuleObjects: List<String> = eeProjects.map { ee ->
    val file = ee.projectDir.resolve("ee-module.properties")
    require(file.isFile) { "${ee.path} has no ee-module.properties naming its ServerModule (see ee/README.md)." }
    // `key=value` lines and `#` comments; read by hand because `java` names the Java extension in this script.
    val name = file.readLines().map(String::trim).firstOrNull { it.startsWith("serverModule=") }
        ?.substringAfter('=')?.trim().orEmpty()
    require(Regex("[a-z][a-z0-9_]*(\\.[a-z][a-z0-9_]*)*\\.[A-Z][A-Za-z0-9_]*").matches(name)) {
        "$file must set serverModule=<fully qualified ServerModule object>, not \"$name\"."
    }
    name
}

val generateEeModules = tasks.register("generateEeModules") {
    val objects = eeModuleObjects
    val output = layout.buildDirectory.dir("generated/ee-modules/kotlin")
    inputs.property("modules", objects)
    outputs.dir(output)
    doLast {
        val directory = output.get().asFile.resolve("run/ostrom/server/app")
        directory.mkdirs()
        val entries = objects.joinToString("") { "    $it,\n" }
        directory.resolve("EeModules.kt").writeText(
            """
            |// Generated by app/build.gradle.kts from ee/modules/*/ee-module.properties: do not edit.
            |package run.ostrom.server.app
            |
            |import run.ostrom.server.kernel.module.ServerModule
            |
            |/** The enterprise modules found in ee/modules/ at build time, none in an Apache-2.0 build without ee/. */
            |internal fun eeModules(): List<ServerModule> = listOf<ServerModule>(
            |$entries)
            |
            """.trimMargin(),
        )
    }
}

kotlin {
    sourceSets {
        commonMain.configure { kotlin.srcDir(generateEeModules) }
        commonMain.dependencies {
            implementation(project(":kernel"))
            rootProject.subprojects
                .filter { it.path.startsWith(":modules:") }
                .forEach { implementation(project(it.path)) }
            eeProjects.forEach { implementation(project(it.path)) }
        }
        // The JVM process, as TeamCode's app (docs/decisions/0001, step 3): Ktor's Netty server, logback behind SLF4J
        // for the libraries' logs, and the CIO client of the telemetry and of every module's engine-less
        // HttpClient { }, with the JDK's TLS.
        jvmMain.dependencies {
            implementation(libs.ktor.server.netty)
            implementation(libs.logback)
            implementation(libs.ktor.client.cio)
        }
        commonTest.dependencies {
            implementation(project(":testing"))
        }
    }
}

// The process entry point (Main.kt: exitProcess; Drain.kt: signals and the stop) runs in the image, whose smoke tests (ci.yml ci-image) start,
// migrate, drain and stop it; what it calls is measured here.
kover {
    reports {
        filters {
            excludes {
                classes(
                    "run.ostrom.server.app.MainKt",
                    "run.ostrom.server.app.MainKt$*",
                    "run.ostrom.server.app.DrainKt",
                    "run.ostrom.server.app.DrainKt$*",
                )
            }
        }
    }
}
