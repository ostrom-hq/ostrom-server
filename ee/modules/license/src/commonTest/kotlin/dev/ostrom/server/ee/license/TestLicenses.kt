private val urlSafe = Base64.UrlSafe.withPadding(Base64.PaddingOption.ABSENT)

/** Base64url without padding, as in a license key. */
fun b64url(bytes: ByteArray): String = urlSafe.encode(bytes)

/** A JSON string literal. */
fun q(value: String): String = "\"$value\""

/**
 * A signing key generated by the test, and what the verifier needs to trust it.
 *
 * @property publicKey Base64 of the DER SubjectPublicKeyInfo.
 * @property keyId 16 hex of SHA-256 of the DER.
 */
class TestSigningKey private constructor(
    private val privateKey: EdDSA.PrivateKey,
    val publicKey: String,
    val keyId: String,
) {
    /**
     * A v1 payload as sign.py writes it, signed by this key. Each change replaces a field's raw JSON; a null value
     * leaves the field out, an unknown name adds it.
     */
    fun payload(vararg changes: Pair<String, String?>): String {
        val fields = linkedMapOf<String, String?>(
            "licenseId" to q("lic_1"),
            "customer" to q("Acme"),
            "issuedAt" to q("2026-10-30T00:00:00Z"),
            "expiresAt" to q("2027-10-30T00:00:00Z"),
            "maxPeople" to "50",
            "features" to "[\"sso\",\"policies\",\"retention\"]",
            "keyId" to q(keyId),
        )
        changes.forEach { (name, json) -> fields[name] = json }
        return fields.entries.filter { it.value != null }.joinToString(",", "{", "}") { "${q(it.key)}:${it.value}" }
    }

    /** Signs [payload] exactly as given and returns the license key. */
    suspend fun sign(payload: String): String {
        val bytes = payload.encodeToByteArray()
        val signature = privateKey.signatureGenerator().generateSignature(bytes)
        return "ostrom-license.v1.${b64url(bytes)}.${b64url(signature)}"
    }

    /** A license key for [payload] with these changes. */
    suspend fun license(vararg changes: Pair<String, String?>): String = sign(payload(*changes))

    /** Generates keys. */
    companion object {
        /** Generates a new key. */
        suspend fun generate(): TestSigningKey {
            val pair = CryptographyProvider.Default.get(EdDSA).keyPairGenerator(EdDSA.Curve.Ed25519).generateKey()
            val der = pair.publicKey.encodeToByteArray(EdDSA.PublicKey.Format.DER)
            val keyId = CryptographyProvider.Default.get(SHA256).hasher().hash(der).toHexString().take(16)
            return TestSigningKey(pair.privateKey, Base64.encode(der), keyId)
        }
    }
}

/** A clock the test moves. */
class MutableClock(var now: Instant = NOW) : Clock {
    override fun now(): Instant = now
}

/** Records log lines, to assert what is logged and that the key never is. */
class RecordingLogger : Logger {
    /** Every line, `LEVEL message fields`. */
    val lines: MutableList<String> = mutableListOf()

    override fun log(level: LogLevel, message: String, fields: Map<String, Any?>, error: Throwable?) {
        lines += "$level $message $fields"
    }

    override fun with(fields: Map<String, Any?>): Logger = this
}

