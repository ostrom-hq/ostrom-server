package run.ostrom.server.ee.license.infrastructure

import run.ostrom.server.ee.license.domain.ExpiredLicenseException
import run.ostrom.server.ee.license.domain.InvalidLicenseSignatureException
import run.ostrom.server.ee.license.domain.LICENSE_CLOCK_SKEW
import run.ostrom.server.ee.license.domain.License
import run.ostrom.server.ee.license.domain.LicenseVerifier
import run.ostrom.server.ee.license.domain.MalformedLicenseException
import run.ostrom.server.ee.license.domain.NotYetValidLicenseException
import run.ostrom.server.ee.license.domain.UnknownLicenseKeyException
import dev.whyoleg.cryptography.CryptographyProvider
import dev.whyoleg.cryptography.algorithms.EdDSA
import dev.whyoleg.cryptography.algorithms.SHA256
import kotlinx.serialization.SerializationException
import kotlin.io.encoding.Base64
import kotlin.time.Instant

/**
 * [LicenseVerifier] on Ed25519 (the JDK through cryptography-kotlin). The key format is
 * `ostrom-license.v1.<base64url(payload JSON)>.<base64url(signature)>`, both parts base64url without padding, the
 * signature made over the payload bytes exactly as encoded (never over a re-serialization).
 *
 * @param trustedKeys The public keys to trust, base64 of the DER SubjectPublicKeyInfo: [PinnedLicenseKeys.ALL] in the
 *   server, a key generated by the test in tests.
 */
class LicenseVerifierImpl(
    private val trustedKeys: List<String> = PinnedLicenseKeys.ALL,
) : LicenseVerifier {
    override suspend fun verify(licenseKey: String, now: Instant): License {
        val key = licenseKey.trim()
        if (key.length > MAX_LENGTH) throw MalformedLicenseException("it is longer than $MAX_LENGTH characters.")
        if (!key.startsWith(PREFIX)) throw MalformedLicenseException("it does not start with $PREFIX")
        val parts = key.removePrefix(PREFIX).split('.')
        if (parts.size != 2) throw MalformedLicenseException("it must be $PREFIX<payload>.<signature>.")
        val payloadBytes = decode(parts[0], "payload")
        val signature = decode(parts[1], "signature")
        // The key id is read before the signature is checked, only to pick the key: nothing else of the payload is
        // trusted until the signature matches.
        val payload = parse(payloadBytes)
        val publicKey = trusted()[payload.keyId] ?: throw UnknownLicenseKeyException(payload.keyId)
        val signed = signature.size == SIGNATURE_SIZE &&
            publicKey.signatureVerifier().tryVerifySignature(payloadBytes, signature)
        if (!signed) throw InvalidLicenseSignatureException()
        val license = payload.toLicense()
        if (now < license.issuedAt - LICENSE_CLOCK_SKEW) throw NotYetValidLicenseException(license.issuedAt)
        if (now > license.graceEndsAt) throw ExpiredLicenseException(license.expiresAt, license.graceEndsAt)
        return license
    }

    private suspend fun trusted(): Map<String, EdDSA.PublicKey> {
        val decoder = CryptographyProvider.Default.get(EdDSA).publicKeyDecoder(EdDSA.Curve.Ed25519)
        val hasher = CryptographyProvider.Default.get(SHA256).hasher()
        return trustedKeys.associate { encoded ->
            val der = Base64.decode(encoded)
            val keyId = hasher.hash(der).toHexString().take(KEY_ID_LENGTH)
            keyId to decoder.decodeFromByteArray(EdDSA.PublicKey.Format.DER, der)
        }
    }

    private fun decode(part: String, name: String): ByteArray = try {
        UNPADDED_URL_SAFE.decode(part)
    } catch (_: IllegalArgumentException) {
        throw MalformedLicenseException("its $name is not base64url without padding.")
    }

    private fun parse(bytes: ByteArray): LicensePayload = try {
        LicenseJson.decodeFromString(LicensePayload.serializer(), bytes.decodeToString())
    } catch (_: SerializationException) {
        // Not JSON, a missing or mistyped field, or a field v1 does not define (LicenseJson).
        throw MalformedLicenseException("its payload is not a v1 license payload.")
    }

    private fun LicensePayload.toLicense(): License {
        fun invalid(field: String): Nothing = throw MalformedLicenseException("its $field is invalid.")
        if (licenseId.isBlank()) invalid("licenseId")
        if (customer.isBlank()) invalid("customer")
        if (maxPeople != null && maxPeople < 1) invalid("maxPeople")
        if (features.any(String::isBlank)) invalid("features")
        if (instanceId != null && instanceId.isBlank()) invalid("instanceId")
        checkTierAndBinding()
        val issued = instant(issuedAt) ?: invalid("issuedAt")
        val expires = instant(expiresAt) ?: invalid("expiresAt")
        if (expires <= issued) invalid("expiresAt")
        return License(licenseId, customer, issued, expires, maxPeople, features.toSet(), instanceId, trial, keyId)
    }

    /** The tier is known, and a license that is not a trial is bound to an instance. */
    private fun LicensePayload.checkTierAndBinding() {
        if (tier != ENTERPRISE_TIER) throw MalformedLicenseException("its tier is invalid.")
        if (!trial && instanceId == null) throw MalformedLicenseException(UNBOUND_REASON)
    }

    private fun instant(value: String): Instant? = try {
        Instant.parse(value)
    } catch (_: IllegalArgumentException) {
        null
    }
}

// File-level rather than in a companion: a private companion's constructor is a line no test can reach (Kover).
private const val PREFIX = "ostrom-license.v1."
private const val ENTERPRISE_TIER = "enterprise"
private const val UNBOUND_REASON = "it is not bound to an instance: a sold enterprise license must carry the id of " +
    "the instance it is for. Send your instance id (GET /api/v1/instance) to sales@ostrom.run to have it re-issued."
private const val MAX_LENGTH = 8_192
private const val SIGNATURE_SIZE = 64
private const val KEY_ID_LENGTH = 16
private val UNPADDED_URL_SAFE = Base64.UrlSafe.withPadding(Base64.PaddingOption.ABSENT)
